#!/usr/bin/env bash
# =============================================================================
# tmux-wait.sh — ждёт окончания серии, запущенной через tmux-run.sh,
# и печатает код выхода и последние строки лога (только итог, не весь лог).
#
# Использование:  scripts/tmux-wait.sh <имя-сессии> [строк-лога=15]
# =============================================================================
REPO="$(cd "$(dirname "$0")/.." && pwd)"
name="$1"; tail_n="${2:-15}"
exitf="$REPO/results/logs/$name.exit"
while [[ ! -f "$exitf" ]]; do sleep 5; done
echo "Серия '$name' завершена, код выхода: $(cat "$exitf")"
tail -n "$tail_n" "$REPO/results/logs/$name.log"
